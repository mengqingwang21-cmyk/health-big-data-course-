def table(name, names=None):
    df=pd.read_csv(T/f'{name}.csv')
    if names: df.columns=names
    def fmt(v):
        if isinstance(v,float): return f'{v:.6f}'
        return str(v)
    rows=['| '+' | '.join(map(str,df.columns))+' |','| '+' | '.join(['---']*len(df.columns))+' |']
    rows += ['| '+' | '.join(fmt(v) for v in row)+' |' for row in df.itertuples(index=False,name=None)]
    return '\n'.join(rows)
def fig(name,alt):
    return f'![{alt}](results/figures/{name}.png)'

